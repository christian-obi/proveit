// Generate test-vectors/eip712.json: ownership signatures made by viem (the library the
// web app uses), so the enclave's Rust verifier is tested against real wallet output.
//
//   node scripts/gen-eip712-vectors.ts
//
// The keys are Anvil's well-known public test keys. They hold nothing; never reuse them.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { hashTypedData } from "viem";
import { privateKeyToAccount } from "viem/accounts";

const SIGNER = privateKeyToAccount("0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80");
const OTHER = privateKeyToAccount("0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d");

// Must match enclave/src/ownership.rs exactly.
export const domain = { name: "Prove-It", version: "1" } as const;
export const types = {
  ProveIt: [
    { name: "statement", type: "string" },
    { name: "account", type: "address" },
    { name: "nearAccount", type: "string" },
    { name: "nonce", type: "uint64" },
    { name: "expiry", type: "uint64" },
  ],
} as const;
export const STATEMENT =
  "I control this Hyperliquid account and allow Prove-It to compute its trading statistics inside a TEE. This signature cannot move funds or place trades.";

const N = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141n;

function highS(sig: `0x${string}`): `0x${string}` {
  const r = sig.slice(2, 66);
  const s = BigInt("0x" + sig.slice(66, 130));
  const v = parseInt(sig.slice(130, 132), 16);
  const flipped = (N - s).toString(16).padStart(64, "0");
  return `0x${r}${flipped}${(v === 27 ? 28 : 27).toString(16)}`;
}

const message = {
  statement: STATEMENT,
  account: SIGNER.address,
  nearAccount: "trader.testnet",
  nonce: 42n,
  expiry: 1_800_000_000n,
};
const typed = { domain, types, primaryType: "ProveIt" as const, message };
const signature = await SIGNER.signTypedData(typed);
const wrongKey = await OTHER.signTypedData(typed);

const proof = (sig: string) => ({
  account: SIGNER.address,
  nearAccount: message.nearAccount,
  nonce: Number(message.nonce),
  expiry: Number(message.expiry),
  signature: sig,
});

const vectors = {
  note: "Generated by scripts/gen-eip712-vectors.ts with viem. Anvil test keys; they hold nothing.",
  domain,
  statement: STATEMENT,
  digest: hashTypedData(typed),
  now: 1_799_990_000,
  valid: proof(signature),
  signed_by_other_key: proof(wrongKey),
  high_s: proof(highS(signature)),
};

writeFileSync(join(import.meta.dirname, "..", "test-vectors", "eip712.json"), JSON.stringify(vectors, null, 2) + "\n");
console.log(`signer ${SIGNER.address}\ndigest ${vectors.digest}`);
