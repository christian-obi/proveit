// Generate test-vectors/merkle.json and test-vectors/card-sig.json from the TypeScript
// verifier (packages/verify), so the Rust enclave is tested against an independent
// implementation of canonical JSON, the Merkle tree and card signing.
//
//   node scripts/gen-p2-vectors.ts
//
// card-sig.json is signed with the PUBLIC test key (seed = sha256("proveit-test-card-key-v1")),
// the same key as enclave/src/platform.rs `test-keys`. Anyone can sign as it.

import { createHash, createPrivateKey, createPublicKey, sign } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { canonical } from "../packages/verify/src/canonical.ts";
import { cardBytes, cardHash, signingMessage } from "../packages/verify/src/card.ts";
import { leafHash, proof, root } from "../packages/verify/src/merkle.ts";

const out = join(import.meta.dirname, "..", "test-vectors");

// ---- Merkle --------------------------------------------------------------------------

const records = [
  { hour: 497_600, coin: "BTC", dir: "Open Long", size_bps: 15_000, pnl_bps: 0, fills: 3 },
  { hour: 497_602, coin: "BTC", dir: "Close Long", size_bps: 15_100, pnl_bps: 212, fills: 1 },
  { hour: 497_650, coin: "ETH", dir: "Open Short", size_bps: 8_000, pnl_bps: 0, fills: 2 },
  { hour: 497_660, coin: "ETH", dir: "Close Short", size_bps: 7_950, pnl_bps: -64, fills: 5 },
  { hour: 497_700, coin: "SOL", dir: "Open Long", size_bps: 3_000, pnl_bps: 0, fills: 1 },
];
const trees = [0, 1, 2, 5].map((n) => {
  const leaves = records.slice(0, n).map((r) => leafHash(canonical(r)));
  return {
    records: records.slice(0, n),
    canonical: records.slice(0, n).map((r) => canonical(r)),
    root: root(leaves),
    proofs: leaves.map((_, i) => proof(leaves, i)),
  };
});
writeFileSync(
  join(out, "merkle.json"),
  JSON.stringify({ note: "Generated by scripts/gen-p2-vectors.ts from packages/verify/src/merkle.ts.", trees }, null, 2) + "\n",
);

// ---- card signature --------------------------------------------------------------------

// Keys deliberately out of order: canonical encoding must sort them.
const card = {
  window: { start: 1791325080034, samples: 46, end: 1793978714143, days: 30 },
  v: 1,
  venue: "hyperliquid",
  stats: {
    win_rate_bps: 6190, return_bps: 1494, max_dd_bps: 6283, trades: 42, profit_factor_x100: 209,
    volume_band: "1e7", active_days: 16, flow_turnover_bps: 661,
  },
  orders: { root: trees[3].root, count: 5 },
  scope: "account",
  outlayer_request_id: null,
  nonce: 42,
  mode: "fixture",
  kind: "trader",
  issuer: "trader.testnet",
  issued_at: 1793980000,
  commitment: "7d2c3f0a9b8e1d6c5f4a3b2e1d0c9b8a7f6e5d4c3b2a19087f6e5d4c3b2a1908",
};

const seed = createHash("sha256").update("proveit-test-card-key-v1").digest();
const privateKey = createPrivateKey({ key: Buffer.concat([Buffer.from("302e020100300506032b657004220420", "hex"), seed]), format: "der", type: "pkcs8" });
const pubkey = createPublicKey(privateKey).export({ format: "der", type: "spki" }).subarray(-32).toString("hex");
const signature = sign(null, signingMessage(card), privateKey).toString("hex");

writeFileSync(
  join(out, "card-sig.json"),
  JSON.stringify(
    {
      note: "Generated by scripts/gen-p2-vectors.ts. Signed with the PUBLIC test key; worthless outside tests.",
      card,
      canonical: cardBytes(card).toString("utf8"),
      card_hash: cardHash(card),
      signing_message: signingMessage(card).toString("hex"),
      pubkey,
      sig: signature,
    },
    null,
    2,
  ) + "\n",
);
console.log(`merkle roots: ${trees.map((t) => t.root.slice(0, 12)).join(" ")}\ncard_hash ${cardHash(card)}\npubkey ${pubkey}`);
